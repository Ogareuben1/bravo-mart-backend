// Configures security headers, CORS, parsing middlewares, static file serving,
// API routes, and global error handling middleware.

import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import path from 'node:path';
import { env } from './config/env.js';
import routes from './routes/index.js';
import { notFound } from './middlewares/notFound.js';
import { errorHandler } from './middlewares/errorHandler.js';

/**
 * Factory function to instantiate a fresh Express application.
 * Facilitates isolation during automated integration testing without binding live ports.
 */
export function createApp(): express.Express {
  const app = express();

  // Sets security-related HTTP headers.
  // Configured crossOriginResourcePolicy to 'cross-origin' so frontend clients on 
  // different origins (e.g., Vite localhost:5173) can display static uploads/images.
  app.use(
    helmet({
      crossOriginResourcePolicy: { policy: 'cross-origin' },
    }),
  );

  // Configure Cross-Origin Resource Sharing for API requests
  app.use(
    cors({
      origin: env.CORS_ORIGIN,
      // Required for browser to send/receive httpOnly refresh cookies cross-origin
      credentials: true,
    }),
  );

  app.use(express.json({ limit: '1mb' }));
  app.use(express.urlencoded({ extended: true }));
  app.use(cookieParser());
  app.use(morgan(env.NODE_ENV === 'development' ? 'dev' : 'combined'));

  // Serve static files uploaded by vendors and generated by AI (KYC docs, product photos)
  // Ensures both dynamic UPLOAD_DIR and explicit '/uploads' route paths resolve to disk
  const uploadPath = path.join(process.cwd(), env.UPLOAD_DIR || 'uploads');
  app.use(`/${env.UPLOAD_DIR || 'uploads'}`, express.static(uploadPath));
  app.use('/uploads', express.static(uploadPath));

  // Health check endpoint for uptime monitoring
  app.get('/health', (_req, res) => {
    res.status(200).json({ status: 'ok', timestamp: new Date().toISOString() });
  });

  // Mount primary API route group
  app.use('/api', routes);

  // Unmatched route handler and central error processing middleware
  app.use(notFound);
  app.use(errorHandler);

  return app;
}