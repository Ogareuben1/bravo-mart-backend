// Configures security headers, CORS, parsing middlewares, static file serving,
// API routes, and global error handling middleware.

import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import path from 'node:path';
import { env } from './config/env.js';
import routes from './routes/index.js';
import { notFound } from './middlewares/notFound.js';
import { errorHandler } from './middlewares/errorHandler.js';

/**
 * Parses comma-separated CORS origins from env (e.g. "https://bravomart.web.app,http://localhost:5173")
 * and strips any accidental trailing slashes.
 */
function getAllowedOrigins(): string[] {
  return env.CORS_ORIGIN.split(',')
    .map((origin) => origin.trim().replace(/\/$/, ''))
    .filter(Boolean);
}

/**
 * Factory function to instantiate a fresh Express application.
 * Facilitates isolation during automated integration testing without binding live ports.
 */
export function createApp(): express.Express {
  const app = express();

  // Required behind Cloud Run / Render load balancers so secure httpOnly cookies
  // and req.ip work properly over HTTPS
  app.set('trust proxy', 1);

  // Sets security-related HTTP headers.
  // Configured crossOriginResourcePolicy to 'cross-origin' so frontend clients on
  // different origins can display static uploads/images.
  app.use(
    helmet({
      crossOriginResourcePolicy: { policy: 'cross-origin' },
    }),
  );

  // Configure Cross-Origin Resource Sharing for API requests
  const allowedOrigins = getAllowedOrigins();

  app.use(
    cors({
      origin(requestOrigin, callback) {
        // Allow server-to-server calls, curl, or health checks with no Origin header
        if (!requestOrigin) {
          return callback(null, true);
        }

        const normalizedOrigin = requestOrigin.replace(/\/$/, '');
        if (allowedOrigins.includes(normalizedOrigin)) {
          return callback(null, true);
        }

        return callback(new Error(`CORS policy blocked origin: ${requestOrigin}`));
      },
      // Required for browser to send/receive httpOnly refresh cookies cross-origin
      credentials: true,
    }),
  );

  app.use(express.json({ limit: '5mb' }));
  app.use(express.urlencoded({ extended: true, limit: '5mb' }));
  app.use(cookieParser());
  app.use(morgan(env.NODE_ENV === 'development' ? 'dev' : 'combined'));

  // Serve static files uploaded by vendors and generated by AI (KYC docs, product photos)
  // Note: For Cloud Run / Render production, persist files in Cloud Storage / Cloudinary
  // since local container disk resets on restart.
  const uploadPath = path.join(process.cwd(), env.UPLOAD_DIR || 'uploads');
  app.use(`/${env.UPLOAD_DIR || 'uploads'}`, express.static(uploadPath));
  app.use('/uploads', express.static(uploadPath));

  // Health check endpoint for uptime monitoring & Cloud Run startup probes
  app.get('/health', (_req, res) => {
    res.status(200).json({ status: 'ok', timestamp: new Date().toISOString() });
  });

  // Mount primary API route group
  app.use('/api', routes);

  // Unmatched route handler and central error processing middleware
  app.use(notFound);
  app.use(errorHandler);

  return app;
}